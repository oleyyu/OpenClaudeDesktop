const declarationEntries = src => [...new Set([...src.top.values()].filter(entry => entry.kind !== 'import'))];
const hasFeatures = (label, text, features) => { try { assertFeatures(label, text, features); return true; } catch { return false; } };
// Unique AST location of every wrapper root, and the facts the facades and the adapter rely on.
async function locateRootsV4() {
  const cache = new Map(), src = await readSlicerSource(W4, cache, official4.ionSource);
  const entries = declarationEntries(src), texts = new Map();
  for (const entry of entries) texts.set(entry, await featureText(src, entry));
  const nameOf = entry => [...src.top].find(([, e]) => e === entry)?.[0];
  const unique = (label, features) => {
    const hits = entries.filter(entry => hasFeatures(label, texts.get(entry), features));
    if (hits.length !== 1) throw Error(`${W4} ${label}: ${hits.length} declarations carry ${JSON.stringify(features)}, expected 1`);
    return hits[0];
  };
  const roots = {};
  for (const [name, root] of Object.entries(wrapperRootsV4)) {
    let entry;
    if (root.ref) {
      const user = unique(`${name} (via ${root.ref.in})`, root.ref.features);
      if (nameOf(user) !== root.ref.in) throw Error(`${W4} ${name}: the declaration using it is ${nameOf(user)}, expected ${root.ref.in}`);
      const used = root.ref.match.exec(texts.get(user))?.[1];
      if (used !== root.local) throw Error(`${W4} ${name}: ${root.ref.in} uses ${used}, expected ${root.local}`);
      entry = src.top.get(root.local);
      assertFeatures(`${W4} ${name} (${root.local})`, texts.get(entry), root.features);
    } else {
      entry = unique(name, root.features);
      if (nameOf(entry) !== root.local) throw Error(`${W4} ${name}: the declaration is ${nameOf(entry)}, expected ${root.local}`);
    }
    roots[name] = { local: root.local, previous: root.old ?? null, features: root.features, ...(root.ref ? { via: root.ref.in } : {}),
      sha256: sha(src.code.slice(entry.node.start, entry.node.end)) };
  }
  // The preload adapter answers `load()`: every preload call of the wrapper names one chunk and no dependencies.
  const preload = [...src.top].find(([, e]) => e.kind === 'import' && e.file === 'preload-helper-BBljBeZo.js' && e.alias === 't')?.[0];
  let calls = 0;
  babel.traverse(babel.babelParse(src.code, W4, true), { CallExpression(p) {
    if (p.node.callee.type !== 'Identifier' || p.node.callee.name !== preload || p.scope.getBinding(preload)?.kind !== 'module') return;
    calls++;
    const [load, deps] = p.node.arguments;
    if (p.node.arguments.length !== 2 || load.type !== 'ArrowFunctionExpression' || deps.type !== 'ArrayExpression' || deps.elements.length)
      throw Error(`${W4}: a preload call passes dependencies or no loader (${src.code.slice(p.node.start, p.node.end).slice(0, 80)})`);
  } });
  if (!preload || calls === 0) throw Error(`${W4}: no preload-helper t calls found`);
  // baseLanguageBehavior: Zc's element texts, their identifiers resolved to the core chunk's aliases or wrapper roots.
  const list = src.top.get(baseLanguageBehaviorV4.list);
  if (list?.kind !== 'var' || list.node.init?.type !== 'ArrayExpression' || list.node.init.elements.length !== baseLanguageBehaviorV4.length)
    throw Error(`${W4} ${baseLanguageBehaviorV4.list} is not the ${baseLanguageBehaviorV4.length}-member base extension list`);
  const localExport = Object.fromEntries(Object.entries(wrapperRootsV4).map(([name, root]) => [root.local, name]));
  const core = new Map(), wrapper = new Map(), members = [];
  for (const [index, expected] of baseLanguageBehaviorV4.members) {
    const node = list.node.init.elements[index], text = src.code.slice(node.start, node.end);
    if (text.replace(/\s+/g, '') !== expected.replace(/\s+/g, '')) throw Error(`${W4} ${baseLanguageBehaviorV4.list}[${index}] is ${text}, expected ${expected}`);
    let globals;
    babel.traverse(babel.babelParse(`(${text});`, `${W4}#Zc[${index}]`, true), { Program(p) { globals = Object.keys(p.scope.globals); p.stop(); } });
    for (const id of globals) {
      const top = src.top.get(id);
      if (top?.kind === 'import' && top.file === CORE4) core.set(id, top.alias);
      else if (localExport[id]) wrapper.set(id, localExport[id]);
      else throw Error(`${W4} ${baseLanguageBehaviorV4.list}[${index}] uses ${id}, neither a ${CORE4} import nor a wrapper root`);
    }
    members.push({ index, text, sha256: sha(text) });
  }
  return { roots, preloadCalls: calls, base: { list: baseLanguageBehaviorV4.list, listSha256: sha(src.code.slice(list.node.start, list.node.end)), members, core, wrapper } };
}
async function facadesV4(manifest, located) {
  const wrapperModule = manifest.modules.find(m => m.source === W4);
  for (const name of [...wrapperFacadeNames, ...themeFacadeNames]) if (wrapperModule.exports[wrapperRootsV4[name].local] !== name) throw Error(`wrapper does not export ${name}`);
  const header = (what) => `// Original Claude Desktop ${official4.referenceVersion}: ${what}; generated by extract-code-editor-current.mjs (facade over ./${wrapperModule.target}).\n// Edit the extractor, never this file.\n`;
  const sorted = list => [...list].sort((a, b) => (a < b ? -1 : 1));
  const { base } = located;
  const wrapperText = await format(`${header('the EpitaxyCodeMirror wrapper (cbd02b8f2) roots the host mounts')}
export { ${sorted(wrapperFacadeNames).join(', ')} } from './${wrapperModule.target}';
import { ${sorted([...base.core].map(([local, alias]) => (local === alias ? local : `${alias} as ${local}`))).join(', ')} } from './${CORE4}';
import { ${sorted([...base.wrapper].map(([local, name]) => `${name} as ${local}`)).join(', ')} } from './${wrapperModule.target}';
// ${base.list} (the editor's base extension list) members ${base.members.map(m => m.index + 1).join(', ')}.
export const baseLanguageBehavior = [${base.members.map(m => m.text).join(', ')}];
`, { parser: 'babel' });
  const themeText = await format(`${header('the editor theme (ws) and its palette (xs)')}
export { ${themeFacadeNames.join(', ')} } from './${wrapperModule.target}';
`, { parser: 'babel' });
  const rootsJson = JSON.stringify({ referenceVersion: official4.referenceVersion, referenceSnapshot: official4.referenceSnapshot, source: W4,
    sourceSha256: wrapperModule.sourceSha256, roots: located.roots, preloadCalls: located.preloadCalls,
    baseLanguageBehavior: { list: base.list, listSha256: base.listSha256, members: base.members.map(({ index, sha256 }) => ({ index, sha256 })) },
    withheld: withheldV4, facades: { 'wrapper.mjs': wrapperFacadeNames.length + 1, 'theme.mjs': themeFacadeNames.length } }, null, 2) + '\n';
  return { 'wrapper.mjs': wrapperText, 'theme.mjs': themeText, 'roots.json': rootsJson };
}
