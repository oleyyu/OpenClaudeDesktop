/**
 * The plugin the bridge installs for OpenCode 2.x (../plugin.js is 1.x's and MiMo's: v2 loads no 1.x hook factory,
 * core/src/plugin/module.ts). v2 takes a configured local plugin only as a directory, so it is
 * <state>/opencode-plugin/code-desktop/index.js, named in OPENCODE_CONFIG_CONTENT (config.js) with the options
 *   { state, wrapper, appTools: {name, command, environment, env, timeout} | null }
 * The module is `export default {id, setup}` and imports nothing beyond node:fs / node:path (no npm install). It reads
 * the same per-session file as 1.x's (<state>/runtime/sessions/<id>.json, index.js writeRuntime) at every hook; a
 * sub-agent without one yet borrows its root's at once (v2 children inherit `metadata.codeDesktop.root`, or walk
 * `parentID`), project instructions excepted. Hooks (packages/plugin/src/promise/*.ts, core/src/plugin/hooks.ts):
 *
 *   session prompt         waits (≤10 s) for the session's file (and its rulesApplied, when the bridge marks it), unless
 *                          it is a sub-agent whose root has one; a sub-agent without its own sandbox file gets a pointer
 *                          to its root (<state>/runtime/sandbox/<id>.root): the shell wrapper reads the root's profile
 *                          at each command, so the root's mode changes reach it (sandbox.js)
 *   session context        (primary steps) a custom system prompt replaces OpenCode's prompt ({{model}}, {{provider}},
 *                          {{cwd}} filled in), keeping only the Code Mode catalog, MCP and skill guidance from the
 *                          instruction sources (without them those tools can't be used); project instructions are
 *                          appended; per-model temperature / maxTokens; the default and final prompt are recorded for
 *                          the preview. claude-agent runs Claude Code's own preset and only appends: there the custom
 *                          prompt is its agent role (options.claudeCodeAgent) and the instructions go in
 *                          options.claudeCodeInstructions; it takes no temperature
 *   permission evaluate    the session's policy (runtime `policy`: mode, planDirs, agentDirs, roots, grants, noUser):
 *                          a read-only mode refuses file edits outside the plan folders, saved "always" rules
 *                          included; an allow only a saved "always" rule gives (a TUI's, same data folder: v2 adds
 *                          them after every session rule) asks again, so the bridge decides it; plan, workspace and
 *                          agent folders need no card; an "Allow for this session" grant answers an ask; an agent
 *                          nobody answers is refused with a reason instead of a card. These refusals are the policy's:
 *                          in-process, no ask, so none of v2's reject-the-whole-batch (v2/asks.js answers the asks)
 *   shell create.before    the shell is the sandbox wrapper, whatever a project's `shell` says (second line: the
 *                          wrapper is also `shell` in OPENCODE_CONFIG_CONTENT and $SHELL)
 *   mcp transform          servers turned off in Customize › Connectors (<state>/mcp.json `disabled`) are disabled (v2
 *                          drops 1.x's {enabled:false} override); OpenClaude Desktop's own server is set with
 *                          codemode:false (its tools stay direct tools), over any same-named one; mcp.json's
 *                          `disabled` changing reloads MCP (mcp.reload), since the config files don't change then and
 *                          v2 reruns transforms only on config.updated
 *
 * OpenClaude Desktop's own tools name the calling session without the plugin: 1.x's hidden argument (SESSION_ARG) would
 * be dropped by v2's input decode for a schema with additionalProperties:false (core/src/tool/runtime.ts), while v2 sends
 * the session in every MCP call's `_meta` (app/electron/agent-tools-opencode.mjs reads it with the runtime files).
 * A hook never throws: v2 turns a failed Promise hook into a defect of the step.
 */

export const PLUGIN_ID = 'code-desktop'
export const PLUGIN_ENTRY = 'index.js'
/** The instruction sources (session/context.ts) a custom system prompt keeps. */
export const KEPT_INSTRUCTIONS = Object.freeze(['core/codemode', 'core/mcp-guidance', 'core/skill-guidance'])

export function pluginSourceV2() {
  return `// Generated by OpenClaude Desktop (harness/packages/opencode-bridge/src/v2/plugin.js). Do not edit.
import fs from "node:fs"
import path from "node:path"

const KEPT = new Set(${JSON.stringify(KEPT_INSTRUCTIONS)})
const CLAUDE_AGENT = "claude-agent"
const READ_ONLY = "This mode cannot change files."
const NO_USER = "Not allowed here: this needs the user\\u2019s approval. This agent runs without approvals and can\\u2019t ask the user, so continue without it."
const safe = (id) => String(id).replace(/[^A-Za-z0-9_-]/g, "_")
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))
const isRecord = (value) => !!value && typeof value === "object" && !Array.isArray(value)
const strings = (list) => (Array.isArray(list) ? list.filter((item) => typeof item === "string" && item) : [])
function interpolate(text, vars) {
  return text.replace(/\\{\\{([a-z][a-z0-9_]*)\\}\\}/g, (match, name) => (typeof vars[name] === "string" ? vars[name] : match))
}
function paramsFor(table, model) {
  if (!isRecord(table) || !model) return undefined
  for (const key of [(model.providerID || "") + "/" + (model.id || ""), model.id]) {
    if (typeof key === "string" && Object.prototype.hasOwnProperty.call(table, key) && isRecord(table[key])) return table[key]
  }
  return undefined
}
// OpenCode's wildcard match (\`*\` any run, \`?\` one character, a trailing " *" also matches nothing).
function wildcard(value, pattern) {
  let source = String(pattern).replace(/[.+^\${}()|[\\]\\\\]/g, "\\\\$&").replace(/\\*/g, ".*").replace(/\\?/g, ".")
  if (source.endsWith(" .*")) source = source.slice(0, -3) + "( .*)?"
  return new RegExp("^" + source + "$", "s").test(String(value))
}
// OpenCode's evaluate: the last rule matching both, else ask.
const evaluate = (rules, action, resource) => (rules.findLast((rule) => isRecord(rule) && wildcard(action, rule.action) && wildcard(resource, rule.resource)) || { effect: "ask" }).effect
const inside = (file, dirs) => dirs.some((dir) => file === dir || file.startsWith(dir.endsWith(path.sep) ? dir : dir + path.sep))
// The texts a custom prompt keeps from OpenCode's instruction part(s) (metadata.experimental.instructions).
function keptInstructions(system) {
  const texts = []
  for (const part of system.slice(1)) {
    const sources = part && part.metadata && part.metadata.experimental && part.metadata.experimental.instructions
    for (const source of Array.isArray(sources) ? sources : []) if (source && KEPT.has(source.key) && typeof source.text === "string" && source.text) texts.push(source.text)
  }
  return texts.join("\\n\\n")
}

export default {
  id: ${JSON.stringify(PLUGIN_ID)},
  setup: async (ctx) => {
    const options = isRecord(ctx && ctx.options) ? ctx.options : {}
    const STATE = typeof options.state === "string" && options.state ? options.state : process.env.CODE_DESKTOP_OPENCODE_STATE || ""
    if (!STATE) return
    const file = (kind, id, ext) => path.join(STATE, "runtime", kind, safe(id) + (ext || ".json"))
    const readJson = (target) => { try { return JSON.parse(fs.readFileSync(target, "utf8")) } catch { return null } }
    const read = (id) => (id ? readJson(file("sessions", id)) : null)
    const ready = (value) => isRecord(value) && value.rulesApplied !== false
    async function waitFor(id, ms) {
      const end = Date.now() + ms
      for (;;) {
        const value = read(id)
        if (ready(value) || Date.now() > end) return value
        await sleep(40)
      }
    }
    function write(kind, id, value) {
      try {
        fs.mkdirSync(path.join(STATE, "runtime", kind), { recursive: true })
        const target = file(kind, id)
        fs.writeFileSync(target + ".tmp", JSON.stringify(value))
        fs.renameSync(target + ".tmp", target)
      } catch {}
    }
    // A sub-agent's root: inherited metadata, else up the parentID chain (the root is the session without a parent).
    const roots = new Map()
    async function rootOf(id) {
      if (roots.has(id)) return roots.get(id)
      let current = id
      for (let depth = 0; depth < 8; depth++) {
        let info = null
        try { info = await ctx.session.get({ sessionID: current }) } catch { break }
        if (isRecord(info) && isRecord(info.data) && info.data.id) info = info.data
        const meta = isRecord(info) && isRecord(info.metadata) && isRecord(info.metadata.codeDesktop) ? info.metadata.codeDesktop : null
        if (meta && typeof meta.root === "string" && meta.root) { roots.set(id, meta.root); return meta.root }
        const parent = isRecord(info) && typeof info.parentID === "string" && info.parentID ? info.parentID : null
        if (!parent) break
        current = parent
      }
      const root = current === id ? null : current
      roots.set(id, root)
      return root
    }
    // The session's own ruleset (the bridge's, PATCHed), or null when it has none.
    async function sessionRules(id) {
      let info = null
      try { info = await ctx.session.get({ sessionID: id }) } catch { return null }
      if (isRecord(info) && isRecord(info.data) && info.data.id) info = info.data
      return isRecord(info) && Array.isArray(info.permissions) && info.permissions.length ? info.permissions : null
    }
    async function inheritedConfig(id) {
      const root = await rootOf(id)
      const inherited = root ? read(root) : null
      return inherited ? { ...inherited, instructions: null, inherited: true } : null
    }
    // The session's runtime file, or its root's at once (minus the root's own project instructions); \`wait\` ms only
    // for a file not ready yet (rulesApplied:false), or when neither the session nor a root has one.
    async function config(id, wait) {
      const own = read(id)
      if (own && (ready(own) || !wait)) return own
      if (!own) {
        const inherited = await inheritedConfig(id)
        if (inherited || !wait) return inherited
      }
      return (await waitFor(id, wait)) || (await inheritedConfig(id))
    }
    // A sub-agent without its own sandbox file points at its root's (the wrapper follows it per command).
    function pointSandbox(id, root) {
      try {
        fs.mkdirSync(path.join(STATE, "runtime", "sandbox"), { recursive: true })
        const target = file("sandbox", id, ".root")
        fs.writeFileSync(target + ".tmp", String(root))
        fs.renameSync(target + ".tmp", target)
      } catch {}
    }

    await ctx.session.hook("prompt", async (event) => {
      try {
        const id = event && event.sessionID
        if (!id) return
        const root = read(id) ? null : await rootOf(id)
        if (root && !fs.existsSync(file("sandbox", id, ".sb"))) pointSandbox(id, root)
        // A sub-agent the bridge has no file for yet runs on its root's (config); anything else waits for its own.
        if (root && ready(read(root))) return
        await waitFor(id, 10000)
      } catch {}
    })

    await ctx.session.hook("context", async (event) => {
      try {
        const id = event.sessionID
        const model = event.model || {}
        const claude = model.providerID === CLAUDE_AGENT
        const system = Array.isArray(event.system) ? event.system : []
        const before = system.map((part) => (part && typeof part.text === "string" ? part.text : ""))
        const runtime = await config(id, 2000)
        if (!isRecord(event.options)) event.options = {}
        const vars = { model: model.id || "", provider: model.providerID || "", cwd: (runtime && runtime.cwd) || (ctx.location && ctx.location.directory) || "" }
        const custom = runtime && typeof runtime.systemPrompt === "string" && runtime.systemPrompt ? interpolate(runtime.systemPrompt, vars) : null
        const instructions = runtime && typeof runtime.instructions === "string" && runtime.instructions ? runtime.instructions : null
        if (claude) {
          if (custom) event.options.claudeCodeAgent = custom
          const base = custom ? keptInstructions(system) : event.options.claudeCodeInstructions
          if (custom || instructions) event.options.claudeCodeInstructions = [base, instructions].filter((text) => typeof text === "string" && text).join("\\n\\n")
        } else {
          if (custom) {
            const kept = keptInstructions(system)
            event.system = [{ type: "text", text: custom }, ...(kept ? [{ type: "text", text: kept }] : [])]
          }
          if (instructions) event.system = [...(Array.isArray(event.system) ? event.system : []), { type: "text", text: instructions }]
        }
        const params = paramsFor(runtime && runtime.modelParams, model)
        if (params && typeof params.temperature === "number" && !claude) event.options.temperature = params.temperature
        if (params && typeof params.maxTokens === "number") event.options.maxTokens = params.maxTokens
        if (id) {
          const previous = readJson(file("prompts", id)) || {}
          write("prompts", id, {
            ...previous, at: Date.now(), model: (model.providerID || "") + "/" + (model.id || ""), default: before,
            final: (Array.isArray(event.system) ? event.system : []).map((part) => (part && typeof part.text === "string" ? part.text : "")), custom: Boolean(custom),
            tools: Object.keys(isRecord(event.tools) ? event.tools : {}),
            ...(claude ? { claudeCode: { agent: event.options.claudeCodeAgent ?? null, instructions: event.options.claudeCodeInstructions ?? null } } : {}),
          })
        }
      } catch {}
    })

    await ctx.permission.hook("evaluate", async (event) => {
      try {
        if (!event || event.effect === "deny") return
        const policy = ((await config(event.sessionID)) || {}).policy
        if (!isRecord(policy) || policy.mode === "bypass") return
        const cwd = typeof policy.cwd === "string" && policy.cwd ? policy.cwd : (ctx.location && ctx.location.directory) || "/"
        const absolute = (resource) => path.resolve(cwd, String(resource).replace(/\\/\\*$/, ""))
        const resources = strings(event.resources)
        const planDirs = strings(policy.planDirs).filter((dir) => path.isAbsolute(dir))
        const readOnly = policy.readOnly === true
        if (event.action === "edit" && readOnly) {
          if (resources.length && resources.map(absolute).every((target) => inside(target, planDirs))) return
          event.effect = "deny"
          event.message = READ_ONLY
          return
        }
        // The session's ruleset comes after the agent's and starts with the bridge's \`* * ask\`: it alone gives what the configured rules give.
        if (event.effect === "allow") {
          const rules = await sessionRules(event.sessionID)
          if (rules && (resources.length ? resources : ["*"]).some((resource) => evaluate(rules, event.action, resource) !== "allow")) event.effect = "ask"
        }
        if (event.effect !== "ask") return
        if (event.action === "external_directory" && resources.length) {
          const targets = resources.map(absolute)
          if (targets.every((target) => inside(target, planDirs))) { event.effect = "allow"; return }
          const own = [cwd, ...strings(policy.roots), ...strings(policy.agentDirs)].filter((dir) => path.isAbsolute(dir))
          if (!readOnly && targets.every((target) => inside(target, own))) { event.effect = "allow"; return }
        }
        if (!readOnly && Array.isArray(policy.grants)) {
          const mine = policy.grants.filter((grant) => isRecord(grant) && (grant.action ?? grant.permission) === event.action)
          const asked = resources.length ? resources : ["*"]
          if (mine.length && asked.every((value) => mine.some((grant) => strings(grant.resources ?? grant.patterns).some((pattern) => wildcard(value, pattern))))) { event.effect = "allow"; return }
        }
        if (policy.noUser === true) { event.effect = "deny"; event.message = NO_USER }
      } catch {}
    })

    const wrapper = typeof options.wrapper === "string" && path.isAbsolute(options.wrapper) ? options.wrapper : null
    await ctx.shell.hook("create.before", async (event) => {
      try { if (wrapper && event) event.shell = wrapper } catch {}
    })

    const app = isRecord(options.appTools) && typeof options.appTools.name === "string" && Array.isArray(options.appTools.command) ? options.appTools : null
    const MCP_FILE = path.join(STATE, "mcp.json")
    const disabledList = () => { const mcp = readJson(MCP_FILE); return strings(mcp && mcp.disabled) }
    await ctx.mcp.transform((editor) => {
      try {
        const disabled = new Set(disabledList())
        for (const name of disabled) if (editor.get(name)) editor.update(name, (server) => { server.disabled = true })
        if (app && !disabled.has(app.name)) {
          // The channel's socket and token come from serve's environment, never from a file.
          const environment = { ...(isRecord(app.environment) ? app.environment : {}) }
          for (const name of strings(app.env)) if (process.env[name]) environment[name] = process.env[name]
          editor.set(app.name, { type: "local", command: strings(app.command), environment, codemode: false, ...(isRecord(app.timeout) ? { timeout: app.timeout } : {}) })
        }
      } catch {}
    })

    // A Connectors switch of the user's own server changes mcp.json only: no config file changes, so v2 publishes no
    // config.updated and never reruns the transform above. The state folder is watched (mcp.json is replaced, not
    // written in place) and MCP reloaded when the disabled list changes.
    const key = () => JSON.stringify(disabledList().sort())
    let seen = key()
    let timer = null
    let watcher = null
    try {
      watcher = fs.watch(STATE, { persistent: false }, (type, name) => {
        if (name && String(name) !== "mcp.json") return
        clearTimeout(timer)
        timer = setTimeout(() => {
          const next = key()
          if (next === seen) return
          seen = next
          if (ctx.mcp && typeof ctx.mcp.reload === "function") Promise.resolve().then(() => ctx.mcp.reload()).catch(() => {})
        }, 150)
      })
      watcher.on("error", () => {})
    } catch {}
    return () => {
      clearTimeout(timer)
      try { if (watcher) watcher.close() } catch {}
    }
  },
}
`
}
