// shared-2 RH / WH requests (source-home-v4-adapters.jsx HOME_MARK_*_EVENT) -> the host's read-state action
// (actions.current.onMarkRead / onMarkUnread; a failure goes to onError). Returns the cleanup.
export function listenHomeReadRequests(target, actions) {
  const forward = name => event => {
    const sessionId = event?.detail?.sessionId;
    const run = actions.current?.[name];
    if (typeof sessionId !== 'string' || !sessionId || typeof run !== 'function') return;
    Promise.resolve().then(() => run(sessionId)).catch(error => actions.current?.onError?.(error));
  };
  const read = forward('onMarkRead'), unread = forward('onMarkUnread');
  target.addEventListener(HOME_MARK_READ_EVENT, read);
  target.addEventListener(HOME_MARK_UNREAD_EVENT, unread);
  return () => { target.removeEventListener(HOME_MARK_READ_EVENT, read); target.removeEventListener(HOME_MARK_UNREAD_EVENT, unread); };
}

/**
 * The 4.16336.0 Cowork home (shared-23 dw: plugin card qx and setup card NC (both off without a marketplace), the task
 * list ZC / QC with the lazily loaded standalone Ideas ce266b9be Le as its empty fallback), generated by
 * scripts/extract-home-v4.mjs over src/source-home-v4-adapters.jsx, in the same below-composer slot as 3.6556.2.
 * Read state stays the host's (main.jsx updateSessionMetadata { unread }): the rows' Clear active / open / Mark as read /
 * Mark as unread reach it through onClearActive / onMarkRead / onMarkUnread.
 */
export function SourceCoworkHome({ call, sessions, metadata, state, ready, sidebarCollapsed = false, onOpen, onOpenRoutine, onClearActive,
  onMarkRead, onMarkUnread, onError, onPrompt, onPreviewPrompt, onFocusInput }) {
  const data = useMemo(() => coworkHomeState(sessions, metadata, state), [sessions, metadata, state]);
  const { tasks, error: scheduleError } = useLocalRoutines(call, 'cowork');
  const scheduledTasks = useMemo(() => (tasks ?? []).map(sourceRoutine), [tasks]);
  const [clearing, setClearing] = useState(null);
  const actions = useRef(null);
  actions.current = { onPrompt, onPreviewPrompt, onFocusInput, onOpen, onOpenRoutine, onMarkRead, onMarkUnread, onError };
  const ideas = useIdeasBridge(actions);
  const navigate = useMemo(() => href => coworkHomeRoute(href, actions.current), []);
  const readState = useMemo(() => {
    const next = { ...data.readState, sessions: { ...data.readState.sessions }, explicitUnread: {} };
    for (const row of data.rows) if (metadata?.[row.sessionId]?.unread) next.explicitUnread[row.sessionId] = true;
    if (clearing) for (const row of data.rows) if (row.lastActivityAt <= (clearing.get(row.sessionId) ?? -1)) {
      next.sessions[row.sessionId] = row.lastActivityAt;
      delete next.explicitUnread[row.sessionId];
    }
    return next;
  }, [data, metadata, clearing]);
  useEffect(() => {
    const clear = async () => {
      if (clearing) return;
      // QC clears its retained row order synchronously (w(BC)) before KH: publish the matching read state in the same
      // event so pending IPC cannot immediately retain them again.
      setClearing(new Map(data.rows.map(row => [row.sessionId, row.lastActivityAt])));
      try { await onClearActive(data.rows); }
      catch (error) { onError?.(error); }
      finally { setClearing(null); }
    };
    window.addEventListener(HOME_CLEAR_EVENT, clear);
    return () => window.removeEventListener(HOME_CLEAR_EVENT, clear);
  }, [data.rows, onClearActive, onError, clearing]);
  useEffect(() => listenHomeReadRequests(window, actions), []);
  const value = useMemo(() => ({ surface: 'cowork', rows: data.rows, readState, ready: ready !== false, permissions: data.permissions,
    scheduledTasks, sidebarCollapsed, ideas, greetings: [], navigate }), [data, readState, ready, scheduledTasks, sidebarCollapsed, ideas, navigate]);
  return <HomeHost.Provider value={value}>
    <div className={`surface-cowork-home ${belowSlotClass}`} role="region" aria-label={t('Cowork tasks')} aria-busy={!!clearing}>
      <CoworkHome />
      {scheduleError && <p role="alert" className="text-body text-danger px-2">{scheduleError}</p>}
    </div>
  </HomeHost.Provider>;
}
