import React, { useEffect, useMemo, useRef, useState } from 'react';
import { CoworkHome } from './generated/cowork-home/index.mjs';
import { CoworkHomeV3Context, HOME_V3_CLEAR_EVENT } from './source-cowork-home-v3-adapters.jsx';
import { RoutinesSharedHost } from './source-routines-shared-adapters.jsx';
import { coworkHomeState } from './cowork-home-model.mjs';
import { t } from '../electron/i18n/index.mjs';
import { useLocalRoutines } from './use-local-routines.jsx';
import { sourceRoutine } from './source-routine-adapters.jsx';

// w10-curchat-home-host: the 3.6556.2 Cowork home (shared-23 FS: the plugin card _b, the setup card rS via
// `setupCard: "task_new"`, the task list xS / SS with the lazily loaded standalone Ideas ce266b9be Re as its
// `emptyFallback`), generated by scripts/extract-cowork-home.mjs over src/source-cowork-home-v3-adapters.jsx.
// The Ideas are the official default arm ("control"); the host no longer filters the catalog (localIdeaIds stays
// exported in source-ideas-adapters.jsx for the 2.31226.0 slice until w10-curchat-retire).
//
// The box is the official below-composer slot (shared-19 composer `h(iu, { className: p(Ne, G), children: V })`):
// Ne = `z ?? (ke ? "mx-auto w-full max-w-[40rem]" : "mx-auto w-full max-w-2xl")` where ke needs shared-78 Fy (the
// voyage_composer_marlin design, off by default here: no GrowthBook payload, device latch "classic"; FS reads the same
// Fy for its "max-w-none px-2" list), G = shared-5 oC(greetingPhoneSeat) for the "home" layout (seat "top" → QS).
// Region / busy attributes are the host's (its clear action is asynchronous).
const belowSlotClass = 'mx-auto w-full max-w-2xl dock:order-2 dock:flex dock:flex-col';

// RouterLink targets of the generated rows (shared-46 Jb `/cowork/${id}`, unencoded as in the original; the scheduled
// rows `/scheduled-task/${encodeURIComponent(id)}`).
const routeId = value => { try { return decodeURIComponent(value); } catch { return value; } };
export function coworkHomeRoute(href, { onOpen, onOpenRoutine }) {
  if (typeof href !== 'string') return;
  if (href.startsWith('/cowork/')) onOpen(routeId(href.slice('/cowork/'.length)));
  else if (href.startsWith('/scheduled-task/')) onOpenRoutine(routeId(href.slice('/scheduled-task/'.length)));
}

export function SourceCoworkHome({ call, sessions, metadata, state, ready, sidebarCollapsed = false, onOpen, onOpenRoutine, onClearActive, onError, onPrompt, onPreviewPrompt, onFocusInput }) {
  const data = useMemo(() => coworkHomeState(sessions, metadata, state), [sessions, metadata, state]);
  const { tasks, error: scheduleError } = useLocalRoutines(call, 'cowork');
  const scheduledTasks = useMemo(() => (tasks ?? []).map(sourceRoutine), [tasks]);
  const [clearing, setClearing] = useState(null);
  const actions = useRef(null);
  actions.current = { onPrompt, onPreviewPrompt, onFocusInput, onOpen, onOpenRoutine };
  // The composer bridge ce266b9be Re writes a picked idea into (shared-5 uA / shared-182 dx / Db).
  const ideas = useMemo(() => {
    const focusInput = () => actions.current.onFocusInput();
    const setPrompt = value => actions.current.onPrompt(value);
    const setTipTapEditorJSON = doc => setPrompt((doc.content ?? []).map(block => (block.content ?? []).map(node => node.text ?? '').join('')).join('\n'));
    return { setPrompt, focusInput, setTipTapEditorJSON,
      promptInputRef: { current: { setContent: setTipTapEditorJSON, focus: focusInput, scrollToEnd: focusInput } },
      setPreviewPrompt: value => actions.current.onPreviewPrompt(value), setPreviewSurface() {},
      // A picked idea's surface is Cowork here (the home is one surface at a time); selection stays on this page.
      pick() {} };
  }, []);
  const host = useMemo(() => ({ navigate: href => coworkHomeRoute(href, actions.current), pathname: '', search: '', bridge: undefined, models: [] }), []);
  const readState = useMemo(() => {
    if (!clearing) return data.readState;
    const next = { ...data.readState, sessions: { ...data.readState.sessions } };
    for (const row of data.rows) if (row.lastActivityAt <= (clearing.get(row.sessionId) ?? -1)) next.sessions[row.sessionId] = row.lastActivityAt;
    return next;
  }, [data, clearing]);
  useEffect(() => {
    const clear = async () => {
      if (clearing) return;
      // SS clears its retained row order synchronously. Publish the matching read
      // state in the same event so pending IPC cannot immediately retain them again.
      setClearing(new Map(data.rows.map(row => [row.sessionId, row.lastActivityAt])));
      try { await onClearActive(data.rows); }
      catch (error) { onError?.(error); }
      finally { setClearing(null); }
    };
    window.addEventListener(HOME_V3_CLEAR_EVENT, clear);
    return () => window.removeEventListener(HOME_V3_CLEAR_EVENT, clear);
  }, [data.rows, onClearActive, onError, clearing]);
  const value = useMemo(() => ({ surface: 'cowork', rows: data.rows, readState, ready: ready !== false, attentionIds: data.attentionIds,
    permissions: data.permissions, scheduledTasks, sidebarCollapsed, ideas }), [data, readState, ready, scheduledTasks, sidebarCollapsed, ideas]);
  return <CoworkHomeV3Context.Provider value={value}>
    <RoutinesSharedHost.Provider value={host}>
      <div className={`surface-cowork-home ${belowSlotClass}`} role="region" aria-label={t('Cowork tasks')} aria-busy={!!clearing}>
        <CoworkHome />
        {scheduleError && <p role="alert" className="text-body text-danger px-2">{scheduleError}</p>}
      </div>
    </RoutinesSharedHost.Provider>
  </CoworkHomeV3Context.Provider>;
}
