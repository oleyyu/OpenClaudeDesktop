// c623cddd3 H `Ke` (the confirmed bulk Archive / Delete): Archive runs over `Y` (the archivable tasks), Delete over every
// selected key; `i` counts the fulfilled runs, `a` the rejections S (shared-104 ti) explains, the failure toast says
// `s = (r.length - i) - a`, and `o === 0 && G.exit()`. The host's archive / delete answers false when called off on
// purpose (a cancelled worktree confirm): explained, counted neither way.
export async function runTasksBulk(ids, run, byId) {
  const settled = await Promise.allSettled(ids.map(id => Promise.resolve().then(() => run(byId.get(id)?.hostSession ?? { id }))));
  const done = [], notDone = [], explained = [];
  settled.forEach((result, at) => {
    const id = ids[at];
    if (result.status === 'fulfilled' && result.value !== false) done.push(id);
    else {
      notDone.push(id);
      if (result.status === 'fulfilled') explained.push(id);
    }
  });
  return { done, notDone, explained, exit: notDone.length === 0 };
}
// H: addSuccess "{count} tasks archived|deleted" for what went (`i > 0`), addError "… could not be …" for the rest (`s > 0`).
export function tasksBulkToasts(outcome, action, intl) {
  const toasts = [];
  if (outcome.done.length > 0) toasts.push({ message: intl.formatMessage(TASKS_PAGE_MESSAGES.done, { count: outcome.done.length, action }), variant: 'neutral' });
  const failed = outcome.notDone.length - outcome.explained.length;
  if (failed > 0) toasts.push({ message: intl.formatMessage(TASKS_PAGE_MESSAGES.failed, { count: failed, action }), variant: 'danger' });
  return toasts;
}
// ye `O` (reportOutcome(targetName, moved, skipped)): both → success "Moved … · {skipped} skipped …", moved only →
// success "Moved {moved} to {targetName}", skipped only → error "Nothing moved — …"; neither → nothing.
export function tasksMoveToast({ moved, skipped, targetName }, intl) {
  if (moved > 0 && skipped > 0) return { message: intl.formatMessage(TASKS_PAGE_MESSAGES.movedSkipped, { moved, skipped, targetName }), variant: 'neutral' };
  if (moved > 0) return { message: intl.formatMessage(TASKS_PAGE_MESSAGES.moved, { moved, targetName }), variant: 'neutral' };
  if (skipped > 0) return { message: intl.formatMessage(TASKS_PAGE_MESSAGES.nothingMoved, { skipped }), variant: 'danger' };
  return null;
}
