// c623cddd3 H: `_ !== "all"` keeps the rows whose archived state is `_ === "archived"`.
export function filterChatsPageRows(rows, filter = CHATS_PAGE_DEFAULT_FILTER) {
  if (filter === 'all') return rows;
  const archived = filter === 'archived';
  return rows.filter(row => row.isArchived === archived);
}

// c623cddd3 `be`: c2b74c150 `a` (R) over {row, title ?? "", summary} with the title / summary keys and L; an empty
// query lists every row; otherwise Fuse, the rows whose first key starts with the query first, then by score.
export function createChatsSearch(rows, { keys = CHATS_SEARCH_KEYS, threshold = CHATS_SEARCH_OPTIONS.threshold } = {}) {
  const search = createFuzzySearch(rows.map(row => ({ row, title: row.title ?? '', summary: row.summary ?? '' })), keys, { threshold });
  return { search: query => search.search(String(query ?? '')).map(result => result.item.row) };
}
// c623cddd3 H: `e ? ve.search(e) : V` with e the trimmed query.
export function searchChatsPageRows(rows, query) {
  return createChatsSearch(rows).search(query);
}

// c623cddd3 H `Y`: a selected row is archivable / movable only when it is a Cowork task (`source.kind === "cowork"`,
// not archived, `sessionType !== "chat"`); `X` drops the ones re (shared-26 PT, a hearthChannelId session; none locally)
// marks unmovable. A chat row is neither, so the bar shows "({count} not movable)" and keeps Move to project / Archive
// disabled for chats, as the official page does.
export function chatsSelectionTargets(selectedKeys, byId) {
  const movable = selectedKeys.filter(id => {
    const row = byId.get(id);
    return row?.ref.kind === 'cowork' && !row.isArchived && row.sessionType !== 'chat';
  });
  return { archivable: movable, movable };
}

