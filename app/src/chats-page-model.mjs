// The rows the page lists, once each. The row shape follows what H reads from its sessions (`ref.id`, `title`,
// `updatedAtMs`; `summary` for `be`), plus the host session for the row menu / delete.
// - Chat alone (Cowork unavailable, CODE_DESKTOP_COWORK=0: shared-78 mY keeps a "chat" surface): the Chat surface's
//   sessions, as the chat list.
// - merged (w13-close-chat-surface, E74; Cowork available, the E60 default): shared-78 mY drops the "chat" surface into
//   "cowork" on the desktop (`u.includes("chat") && (a || …) → ["cowork", ...u.filter(hY)]`), and the /chats route
//   (shared-18 aR: `as()` = shared-78 gK, a store selector that is always true → iR → ChatsPageClient) is H itself:
//   `ue({includeArchivedCowork: !0, keepSessionsOpenedAsChats: !0})` filtered by Te (`e.ref.kind === "cowork" && !N(e)`),
//   N = shared-11 hw → shared-52 $O (`!!e.scheduledTaskId || e.sessionType === "dispatch_child"`). A local chat is a
//   cowork-source session with sessionType "chat" (local_agent_mode_session), so Chat and Cowork sessions share one list;
//   scheduled-task runs stay out. No server condition is involved (shared-78 gv tourOneListTitle, "Your chats and tasks
//   in one list", is only defined: no chunk reads it).
export function chatsPageRows(sessions = [], { metadata = {}, merged = false } = {}) {
  const seen = new Set();
  const rows = [];
  for (const session of Array.isArray(sessions) ? sessions : []) {
    const surface = session?.id ? sessionSurface(session.id, metadata) : null;
    if (!session?.id || seen.has(session.id) || !(surface === 'chat' || (merged && surface === 'cowork'))) continue;
    if (merged && (metadata?.[session.id]?.scheduledTaskId != null || session.scheduledTaskId != null)) continue;
    seen.add(session.id);
    const title = (typeof session.name === 'string' && session.name.trim()) || (typeof session.title === 'string' && session.title.trim()) || null;
    rows.push({
      ref: { kind: merged ? 'cowork' : 'chat', id: session.id },
      sessionType: surface === 'chat' ? 'chat' : 'cowork',
      title,
      summary: typeof session.preview === 'string' ? session.preview : '',
      updatedAtMs: sessionUpdatedAt(session),
      isArchived: sessionArchived(session),
      hostSession: session,
    });
  }
  return rows.sort((a, b) => b.updatedAtMs - a.updatedAtMs);
}
