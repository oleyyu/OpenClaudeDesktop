test('code imports view-tabs by semantic name from current files or the facade; nothing imports a 2.42304.0 file name (R6, W7)', () => {
  const sources = [];
  const walk = dir => { for (const entry of fs.readdirSync(dir, {withFileTypes:true})) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) { if (file !== directory) walk(file); }
    else if (/\.(m?js|jsx)$/.test(entry.name)) sources.push(file);
  } };
  walk(path.join(app, 'src')); walk(path.join(app, 'electron')); sources.push(path.join(app, 'scripts/extract-code-ui-current.mjs'));
  const current = new Map();
  for (const [name, {file}] of Object.entries(manifest.publicNames)) (current.get(file) ?? current.set(file, new Set()).get(file)).add(name);
  current.set(manifest.facade, new Set(Object.keys(manifest.publicNames)));
  let checked = 0;
  for (const file of sources) {
    const text = fs.readFileSync(file, 'utf8');
    for (const [, names, target] of text.matchAll(/(?:import|export)\s*\{([^}]*)\}\s*from\s*['"][^'"]*view-tabs\/([^'"/]+\.js)['"]/g)) {
      // Strict: no file, host or generated, imports a file the 3.6556.2 graph does not write.
      assert.ok(current.has(target), `${path.relative(app, file)} imports ${target}, which is not a current view-tabs file`);
      const allowed = current.get(target);
      for (const spec of names.split(',').map(s => s.trim()).filter(Boolean)) {
        const imported = spec.split(/\s+as\s+/)[0];
        assert.ok(allowed.has(imported), `${path.relative(app, file)} imports ${imported} from ${target}`);
        checked++;
      }
    }
  }
  assert.ok(checked >= 30, `only ${checked} imports checked`);
});
