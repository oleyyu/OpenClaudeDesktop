// The shared view-tab graph is extracted from the installed 2.42304.0 renderer.
// These checks read only the local reference copy and the generated output.
const app = path.resolve(import.meta.dirname, '..');
const directory = path.join(app, 'src/generated/view-tabs');
const manifest = JSON.parse(fs.readFileSync(path.join(directory, 'manifest.json'), 'utf8'));
const reference = path.resolve(app, '../reference', manifest.referenceSnapshot, 'ion-dist/assets/v1');
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const header = '// Original Claude Desktop 2.42304.0 bindings; generated by extract-view-tabs.mjs.\n';
let server; const loaded = new Map();
before(async () => {
  server = await createServer({configFile:false, root:app, plugins:[react()], server:{middlewareMode:true, hmr:false, watch:null}, appType:'custom', logLevel:'error'});
  for (const {file} of Object.values(manifest.publicNames)) if (!loaded.has(file)) loaded.set(file, await server.ssrLoadModule(`/src/generated/view-tabs/${file}`));
});
after(() => server?.close());
const exported = name => loaded.get(manifest.publicNames[name].file)[name];

test('manifest pins the installed 2.42304.0 snapshot and every module hashes to its reference source and output', () => {
  assert.equal(manifest.referenceVersion, '2.42304.0');
  assert.equal(manifest.referenceSnapshot, 'installed-2.42304.0-20261017');
  assert.equal(manifest.modules.length, 28);
  for (const module of manifest.modules) {
    assert.equal(sha(fs.readFileSync(path.join(reference, module.source))), module.sourceSha256, module.source);
    const text = fs.readFileSync(path.join(directory, module.source), 'utf8');
    assert.equal(sha(text), module.sha256, module.source);
    assert.ok(text.startsWith(header), module.source);
    assert.equal(typeof module.dynamic, 'boolean');
  }
  assert.deepEqual(manifest.modules.filter(m => m.dynamic).map(m => m.source), ['c86ccec3d-zuivwocA.js']);
});

