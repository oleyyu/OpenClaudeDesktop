  assert.match(render(h(exported('CdsCheckbox'), {label:'Select', checked:true, onCheckedChange(){}})), /role="checkbox"[^>]*aria-checked="true"[^>]*data-cds="Checkbox"/);
  assert.equal(typeof exported('CdsTextInput').render, 'function');
