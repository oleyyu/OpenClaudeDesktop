  const split = render(provider(h(exported('CdsSplitDropdownButton'), {label:'Send', onPrimaryClick(){}, items:[{label:'Queue for later', onClick(){}}]})));
  assert.match(split, /^<div data-cds="SplitDropdownButton" role="group" aria-label="Send"/);
  assert.match(split, /data-cds="Button"/);
