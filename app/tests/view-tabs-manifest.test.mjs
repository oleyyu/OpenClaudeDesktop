const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const header = '// Original Claude Desktop 3.6556.2 bindings; generated by extract-view-tabs.mjs.\n';
const frame = 'shared-frame-6jtSkIit.js', vendorFrame = 'vendor-frame-CnSY1sxv.js';
let server; const loaded = new Map();
const load = async file => { if (!loaded.has(file)) loaded.set(file, await server.ssrLoadModule(`/src/generated/view-tabs/${file}`)); return loaded.get(file); };
// The graph reaches host adapters (code-start -> chat -> home ...) whose top level may start an import() it does not
// await. Closing the server while one is in flight rejects it after the hook ("transport was disconnected, cannot call
// fetchModule") and fails the whole file, so the hook waits until the SSR runner has nothing pending before it returns.
const settle = async () => {
  const runner = server._ssrCompatModuleRunner;
  for (let idle = 0; idle < 2;) {
    const pending = [...runner.concurrentModuleNodePromises.values(), runner.builtinsPromise,
      ...[...runner.evaluatedModules.idToModuleMap.values()].filter(m => m.promise && !m.evaluated).map(m => m.promise)].filter(Boolean);
    if (pending.length) { idle = 0; await Promise.allSettled(pending); }
    else idle++;
    await new Promise(resolve => setImmediate(resolve));
  }
};
before(async () => {
  server = await createServer({configFile:false, root:app, plugins:[react()], server:{middlewareMode:true, hmr:false, ws:false, watch:null}, appType:'custom', logLevel:'error'});
  for (const {file} of Object.values(manifest.publicNames)) await load(file);
  await settle();
});
after(() => server?.close());
const exported = name => loaded.get(manifest.publicNames[name].file)[name];

