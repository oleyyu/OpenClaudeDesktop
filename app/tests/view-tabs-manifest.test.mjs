test('the routines graphs import view-tabs by semantic name, or by local only for a held-back name (D46)', () => {
  const held = new Set(manifest.modules.flatMap(m => m.bindings.map(b => `${m.source}#${b}`)));
  // pendingNames: settled D46 names other areas' generators still slice; never also published.
  const pendingByLocal = new Map(Object.entries(manifest.pendingNames).map(([name, {file, local}]) => [`${file}#${local}`, name]));
  for (const name of Object.keys(manifest.pendingNames)) assert.ok(!(name in manifest.publicNames), name);
  for (const {file, local, waitsFor} of Object.values(manifest.pendingNames)) {
    assert.ok(held.has(`${file}#${local}`)); assert.ok(waitsFor.length > 0);
    for (const generator of waitsFor) assert.ok(fs.existsSync(path.join(app, 'scripts', `extract-${generator}.mjs`)), generator);
  }
  let named = 0;
  for (const dir of ['routines-shared', 'code-routines', 'cowork-scheduled']) {
    const generated = JSON.parse(fs.readFileSync(path.join(app, 'src/generated', dir, 'manifest.json'), 'utf8'));
    const text = JSON.stringify(generated);
    for (const [, from, name, kind] of text.matchAll(/"from":"\.\.\/view-tabs\/([^"]+)","name":"([^"]+)","kind":"(view-tabs(?:-held)?)"/g)) {
      if (kind === 'view-tabs') { assert.equal(manifest.publicNames[name]?.file, from, `${dir}: ${from}#${name}`); named++; }
      else assert.ok(pendingByLocal.has(`${from}#${name}`), `${dir}: ${from}#${name} is imported by its local without a pending D46 name`);
    }
    for (const m of generated.modules) for (const b of m.bindings ?? [])
      assert.ok(!held.has(`${m.source}#${typeof b === 'string' ? b : b.name}`), `${dir}: ${m.source}#${b.name ?? b} is copied a second time`);
  }
  assert.ok(named >= 150, `only ${named} named view-tabs imports`);
  // The generators refuse a held binding without a name instead of importing its minified local.
  for (const generator of ['extract-routines-shared.mjs', 'extract-code-routines.mjs', 'extract-cowork-scheduled.mjs'])
    assert.match(fs.readFileSync(path.join(app, 'scripts', generator), 'utf8'), /is held by view-tabs without a semantic name; name it in extract-view-tabs\.mjs \(D46\)/, generator);
});

test('host code imports view-tab modules only through semantic public names', () => {
  const sources = [];
  const walk = dir => { for (const entry of fs.readdirSync(dir, {withFileTypes:true})) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) { if (file !== directory) walk(file); }
    else if (/\.(m?js|jsx)$/.test(entry.name)) sources.push(file);
  } };
  walk(path.join(app, 'src')); sources.push(path.join(app, 'scripts/extract-code-ui-current.mjs'));
  const publicByFile = new Map();
  for (const [name, {file}] of Object.entries(manifest.publicNames)) publicByFile.set(file, [...(publicByFile.get(file) ?? []), name]);
  let checked = 0;
  for (const file of sources) {
    const text = fs.readFileSync(file, 'utf8');
    for (const [, names, target] of text.matchAll(/(?:import|export)\s*\{([^}]*)\}\s*from\s*['"][^'"]*view-tabs\/([^'"/]+\.js)['"]/g)) {
      assert.ok(publicByFile.has(target), `${path.relative(app, file)} -> ${target}`);
      for (const spec of names.split(',').map(s => s.trim()).filter(Boolean)) {
        const imported = spec.split(/\s+as\s+/)[0];
        assert.ok(publicByFile.get(target).includes(imported), `${path.relative(app, file)} imports ${imported} from ${target}`);
        checked++;
      }
    }
  }
  assert.ok(checked >= 30, `only ${checked} imports checked`);
});
