// vYe with the props lYe computes once the hash is known; the AppRenderer chunk is a probe recording its props.
function renderWidget(props = {}) {
  const seen = [];
  const handle = Card.appRendererChunk.handle;
  const saved = { module: handle.module, resident: handle.resident, ssr: handle.ssr };
  assert.equal(handle.ssr, false, 'qJ is ssr:false');
  // The probe stands in for the resident AppRenderer (test only: the server render draws it).
  handle.module = function Probe(p) { seen.push(p); return h('div', { 'data-probe': '' }); };
  handle.resident = true;
  handle.ssr = true;
  try {
    const match = props.match ?? visualizeMatch();
    const html = renderToStaticMarkup(h(Card.McpAppWidgetCard, {
      tool: { id: 'call-1', name: 'mcp__visualize__show_widget', status: 'completed', input: { title: 'Chart' }, rawResultContent: [{ type: 'text', text: 'ok' }] },
      sessionRef: { type: 'local', id: 's1' }, sharesWithSession: true, match, serverUuid: match?.server.uuid, serverIdentifier: match?.server.uuid,
      sessionOwned: false, isSshHostEntry: false, firstPartyServer: true, client: { getServerCapabilities: () => ({ resources: {} }) },
      sandboxProxyUrl: new URL(Adapters.MCP_APP_SANDBOX_PROXY_URL), conversationHash: HASH, expanded: true, onToggleExpanded() {}, loadAttempt: 's1\u00000',
      onInitError() {}, onHoldsRow() {}, heldRowHeight: undefined, onInitialized() {}, hostResident: false, reservedHeight: 0, drawnWhileWritten: false,
      savesViewState: true, ...props }));
    return { html, props: seen.at(-1) };
  } finally { Object.assign(handle, saved); }
}

